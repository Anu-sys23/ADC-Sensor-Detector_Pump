void ADS131M04_ReadData(void)
{
    // Wait until DRDY becomes LOW
    uint32_t timeout = HAL_GetTick();

    while(HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_4) == GPIO_PIN_SET)
    {
        if(HAL_GetTick() - timeout > 100)
        {
            return;  // Timeout
        }
    }

    // Send NULL command and receive ADC data
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_15, GPIO_PIN_RESET);

    HAL_SPI_TransmitReceive(&hspi3,
                            txData,
                            rxData,
                            18,
                            100);

    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_15, GPIO_PIN_SET);

    // First frame: send NULL command, discard old response
    if(firstRead == 1)
    {
        firstRead = 0;
        return;
    }

    // Extract Channel 0 (bytes 3, 4, 5)
    ADC_CH0 = ((int32_t)rxData[3] << 16) |
              ((int32_t)rxData[4] << 8)  |
              ((int32_t)rxData[5]);

    // Extract Channel 1 (bytes 6, 7, 8)
    ADC_CH1 = ((int32_t)rxData[6] << 16) |
              ((int32_t)rxData[7] << 8)  |
              ((int32_t)rxData[8]);

    // Extract Channel 2 (bytes 9, 10, 11)
    ADC_CH2 = ((int32_t)rxData[9] << 16) |
              ((int32_t)rxData[10] << 8) |
              ((int32_t)rxData[11]);

    // Extract Channel 3 (bytes 12, 13, 14)
    ADC_CH3 = ((int32_t)rxData[12] << 16) |
              ((int32_t)rxData[13] << 8) |
              ((int32_t)rxData[14]);


    // Convert 24-bit signed data into signed 32-bit data

    if(ADC_CH0 & 0x800000) ADC_CH0 |= 0xFF000000;
    if(ADC_CH1 & 0x800000) ADC_CH1 |= 0xFF000000;
    if(ADC_CH2 & 0x800000) ADC_CH2 |= 0xFF000000;
    if(ADC_CH3 & 0x800000) ADC_CH3 |= 0xFF000000;
//    ADC_CH0 =  ADC_CH0 * 0.196695;
//    ADC_CH1=  ADC_CH1* 0.196695;
//	ADC_CH2 =  ADC_CH2* 0.196695;
//	ADC_CH3= ADC_CH3* 0.196695;
}

void ADS131M04_PrintData(void)
{
    char msg[200];

    sprintf(msg,
            "\r\nADC CHANNEL VALUES\r\n"
            "CH0 = %ld\r\n"
            "CH1 = %ld\r\n"
            "CH2 = %ld\r\n"
            "CH3 = %ld\r\n"
            "------------------------\r\n",
            (long)ADC_CH0,
            (long)ADC_CH1,
            (long)ADC_CH2,
            (long)ADC_CH3);

    HAL_UART_Transmit(&huart1,
                      (uint8_t *)msg,
                      strlen(msg),
                      HAL_MAX_DELAY);
}



